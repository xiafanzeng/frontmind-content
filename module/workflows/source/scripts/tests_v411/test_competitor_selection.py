    def test_scope_modes_change_with_the_selected_objects(self):
        self.research_pause()
        cases = [
            (self.selection(("c001",), ("c002",)), "between_types"),
            (self.selection(("c002",), ()), "within_type"),
            (self.selection(("c001", "c002"), ()), "mixed"),
            (self.selection(("c004",), ("c002",)), "between_types"),
        ]
        for index, (chosen, expected_mode) in enumerate(cases):
            with self.subTest(mode=expected_mode, targets=chosen["comparison_targets"]):
                if index:
                    self.cont("--return-to-competitors")
                calls = self.confirm_scope(chosen)
                self.assertEqual([SYNTHESIS_ACTION], [call["action"] for call in calls])
                scope = self.read(CORE_PATH)["comparison_scope"]
                self.assertEqual(expected_mode, scope["mode"])
                if "c002" in chosen["comparison_targets"]:
                    self.assertIn(PEER_MARKER, calls[0]["market_input"])
                else:
                    self.assertNotIn(PEER_MARKER, calls[0]["market_input"])

