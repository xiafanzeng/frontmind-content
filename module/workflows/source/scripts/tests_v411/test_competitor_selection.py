    def test_two_ready_returns_export_v2_then_v3_without_modifying_prior_packs(self):
        self.research_pause()
        self.confirm_scope()
        self.cont("--confirm-core-positioning")
        first_delivery = deepcopy(state(self.job)["metadata"]["reference_pack_delivery"])
        first_pack = Path(first_delivery["pack_path"])
        first_zip = Path(first_delivery["portable_zip_path"])

        def snapshot(directory):
            return {str(path.relative_to(directory)): hashlib.sha256(path.read_bytes()).hexdigest()
                    for path in directory.rglob("*") if path.is_file()}

        original_files = snapshot(first_pack)
        original_zip_digest = hashlib.sha256(first_zip.read_bytes()).hexdigest()
        first_core = json.loads((first_pack / "strategy/core_positioning.json").read_text(encoding="utf-8"))
        self.assertEqual(1, first_delivery["pack_version"])
        self.assertEqual("between_types", first_core["comparison_scope"]["mode"])

        self.cont("--return-to-competitors")
        revised = {**CORE, "core_positioning_paragraph": f"{BRAND}的新比较范围使用这一版说明。V2_SCOPE_VALUE_8036"}
        self.confirm_scope(self.selection(("c002",), ()), core=revised)
        second_core = self.read(CORE_PATH)
        self.assertEqual("within_type", second_core["comparison_scope"]["mode"])
        self.assertGreater(second_core["comparison_scope"]["revision"], first_core["comparison_scope"]["revision"])
        self.cont("--confirm-core-positioning")

        self.assertEqual("positioning_ready", state(self.job)["status"])
        second_delivery = state(self.job)["metadata"]["reference_pack_delivery"]
        second_pack = Path(second_delivery["pack_path"])
        second_zip = Path(second_delivery["portable_zip_path"])
        self.assertEqual(2, second_delivery["pack_version"])
        self.assertEqual(first_delivery["pack_id"], second_delivery["pack_id"])
        self.assertNotEqual(first_pack, second_pack)
        self.assertNotEqual(first_zip, second_zip)
        self.assertTrue(second_zip.is_file())
        self.assertEqual(second_core, json.loads((second_pack / "strategy/core_positioning.json").read_text(encoding="utf-8")))
        self.assertEqual(["同类服务乙"], self.names(second_core["comparison_scope"]["comparison_targets"]))
        self.assertEqual([], second_core["comparison_scope"]["peer_examples"])
        self.assertEqual(original_files, snapshot(first_pack))
        self.assertEqual(original_zip_digest, hashlib.sha256(first_zip.read_bytes()).hexdigest())

        second_files = snapshot(second_pack)
        second_zip_digest = hashlib.sha256(second_zip.read_bytes()).hexdigest()
        self.cont("--return-to-competitors")
        third_value = {**CORE, "core_positioning_paragraph": f"{BRAND}同时比较不同类型及同类服务。V3_SCOPE_VALUE_5804"}
        self.confirm_scope(self.selection(("c001", "c002"), ()), core=third_value)
        third_core = self.read(CORE_PATH)
        self.assertEqual("mixed", third_core["comparison_scope"]["mode"])
        self.cont("--confirm-core-positioning")
        third_delivery = state(self.job)["metadata"]["reference_pack_delivery"]
        self.assertEqual(3, third_delivery["pack_version"])
        self.assertEqual(first_delivery["pack_id"], third_delivery["pack_id"])
        third_pack = Path(third_delivery["pack_path"])
        self.assertNotIn(third_pack, (first_pack, second_pack))
        self.assertEqual(third_core, json.loads((third_pack / "strategy/core_positioning.json").read_text(encoding="utf-8")))
        self.assertEqual(original_files, snapshot(first_pack))
        self.assertEqual(second_files, snapshot(second_pack))
        self.assertEqual(original_zip_digest, hashlib.sha256(first_zip.read_bytes()).hexdigest())
        self.assertEqual(second_zip_digest, hashlib.sha256(second_zip.read_bytes()).hexdigest())

