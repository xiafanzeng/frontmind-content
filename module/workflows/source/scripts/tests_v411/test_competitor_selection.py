class CompetitorSelectionTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="frontmind-competitor-scope-")
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name)
        self.job = self.base / "job"
        material = self.base / "company.md"
        material.write_text(
            f"{BRAND}属于{BRAND_CATEGORY}，为周期性任务提供持续安排。ORIGINAL_SCOPE_MATERIAL",
            encoding="utf-8",
        )
        with mock.patch.object(C, "invoke_external_provider", return_value=False):
            self.command("reference-pack", "create", "--brand", BRAND,
                         "--input", str(material), "--job-dir", str(self.job))
        self.assertEqual(RESEARCH_ACTION, state(self.job)["pending_action"]["action"])

    def command(self, *args):
        arguments = C.parser().parse_args(list(args))
        with redirect_stdout(io.StringIO()):
            return arguments.func(arguments)

    def cont(self, *args, revision=None):
        current_revision = state(self.job)["revision"] if revision is None else revision
        return self.command("continue", "--job-dir", str(self.job),
                            "--revision", str(current_revision), *args)

    def read(self, member):
        return json.loads((self.job / member).read_text(encoding="utf-8"))

    def run_provider(self, *, research=None, core=None, callback=None):
        outputs = {
            RESEARCH_ACTION: RESEARCH if research is None else research,
            SYNTHESIS_ACTION: CORE if core is None else core,
        }
        calls = []

        def provider(request_path, request, job):
            action = request["action"]
            self.assertIn(action, outputs, "No unrelated Provider action should run")
            market_path = job / "inputs/market_research.md"
            calls.append({
                "action": action,
                "prompt": (job / request["prompt_path"]).read_text(encoding="utf-8"),
                "market_input": market_path.read_text(encoding="utf-8") if market_path.exists() else "",
                "scope": deepcopy(state(job).get("decisions", {}).get("comparison_scope")),
            })
            C.atomic_json(job / request["expected_output"], deepcopy(outputs[action]))
            return True

        with mock.patch.object(C, "invoke_external_provider", side_effect=provider), redirect_stdout(io.StringIO()):
            result = callback() if callback else C.drive(self.job)
        self.assertEqual(0, result)
        return calls

    def research_pause(self):
        calls = self.run_provider()
        self.assertEqual([RESEARCH_ACTION], [call["action"] for call in calls])
        self.assertEqual("awaiting_competitor_selection", state(self.job)["status"])
        return calls

    def selection(self, targets=("c001",), peers=("c002",)):
        return {"comparison_targets": list(targets), "peer_examples": list(peers)}

    def confirm_scope(self, selection=None, **provider_kwargs):
        chosen = self.selection() if selection is None else selection
        return self.run_provider(
            callback=lambda: self.cont("--competitor-selection", json.dumps(chosen, ensure_ascii=False),
                                       "--confirm-competitors"),
            **provider_kwargs,
        )

    def names(self, items):
        candidates = {item["id"]: item["name"] for item in self.read(MARKET_PATH)["competitor_candidates"]}
        return [item["name"] if isinstance(item, dict) else candidates[item] for item in items]

