def candidate(name, category, kind, notes, role, url, *, relation=None):
    item = {
        "name": name,
        "category": category,
        "kind": kind,
        "research_notes": notes,
        "source_urls": [url],
        "suggested_role": role,
    }
    if relation is not None:
        item["relation_to_brand"] = relation
    return item


