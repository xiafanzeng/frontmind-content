def stage_role(action: str) -> str:
    roles = {
        "p0_blueprint": "你是智谱Managed Agent宿主，按篇读取企业原件、选择事实并整理内容任务，不写成稿。本阶段不读取任何品宣例文；例文只在第三遍载入。\n" + SELECTION,
        "p0_draft": DRAFT,
        "p0_edit": EDIT,
    }
    return roles[action] + "\n" + COMMON
