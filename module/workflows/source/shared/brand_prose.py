def stage_role(action: str) -> str:
    stage = action.removeprefix("p0_")
    if stage not in ROLES:
        raise ValueError("unsupported prose stage")
    return ROLES[stage] + "\n\n" + CORE + "\n只返回当前动作要求的结果结构。后台过程、自评和来源说明不进入公开正文。"


def refine_prompt(prompt: str, stage: str) -> str:
    """Keep full evidence/examples and the original result schema, not a summary."""
    first, sep, rest = prompt.partition("\n")
    return first + sep + MARKER + "\n\n## 本轮出版表达要求\n\n" + ROLES[stage] + "\n\n" + rest
